function interp(ages: number[], arr: number[], age: number): number {
  if (age <= ages[0]) return arr[0]
  if (age >= ages[ages.length - 1]) return arr[arr.length - 1]
  for (let i = 0; i < ages.length - 1; i++) {
    if (age >= ages[i] && age <= ages[i + 1]) {
      const t = (age - ages[i]) / (ages[i + 1] - ages[i])
      return arr[i] + t * (arr[i + 1] - arr[i])
    }
  }
  return arr[arr.length - 1]
}

export function classifyPercentile(value: number, ageYears: number, dataset: Record<string, GenderData>, sex: string) {
  const d = ageYears <= 2 ? dataset[sex].monthly : dataset[sex].yearly
  const ages = ageYears <= 2 ? d.ages.map((m: number) => m / 12) : d.ages
  const p3  = interp(ages, d.p3,  ageYears)
  const p15 = interp(ages, d.p15, ageYears)
  const p50 = interp(ages, d.p50, ageYears)
  const p85 = interp(ages, d.p85, ageYears)
  const p97 = interp(ages, d.p97, ageYears)
  if (value < p3)  return { label: '< P3',      zone: 'critical_low' }
  if (value < p15) return { label: 'P3 – P15',  zone: 'low' }
  if (value < p50) return { label: 'P15 – P50', zone: 'normal' }
  if (value < p85) return { label: 'P50 – P85', zone: 'normal' }
  if (value < p97) return { label: 'P85 – P97', zone: 'high' }
  return               { label: '> P97',      zone: 'critical_high' }
}

export function calcIdadeAnos(dataNascimento: string, dataRef?: string): number {
  const nasc = new Date(dataNascimento)
  const ref  = dataRef ? new Date(dataRef) : new Date()
  return (ref.getTime() - nasc.getTime()) / (1000 * 60 * 60 * 24 * 365.25)
}

export function getChartSeries(dataset: Record<string, GenderData>, sex: string, ageYears: number) {
  const useMonthly = ageYears <= 2
  const d = useMonthly ? dataset[sex].monthly : dataset[sex].yearly
  const ages = useMonthly ? d.ages.map((m: number) => parseFloat((m / 12).toFixed(3))) : d.ages
  return { ages, p3: d.p3, p15: d.p15, p50: d.p50, p85: d.p85, p97: d.p97, xLabel: useMonthly ? 'Meses' : 'Anos' }
}
