function interp(ages: number[], arr: number[], age: number): number {
  if (age <= ages[0]) return arr[0]
  if (age >= ages[ages.length - 1]) return arr[arr.length - 1]
  for (let i = 0; i < ages.length - 1; i++) {
    if (age >= ages[i] && age <= ages[i + 1]) {
      const t = (age - ages[i]) / (ages[i + 1] - ages[i])
      return arr[i] + t * (arr[i + 1] - arr[i])
    }
  }
  return arr[arr.length - 1]
}

export function calcIdadeAnos(dataNascimento: string, dataRef?: string): number {
  const nasc = new Date(dataNascimento)
  const ref = dataRef ? new Date(dataRef) : new Date()
  return (ref.getTime() - nasc.getTime()) / (1000 * 60 * 60 * 24 * 365.25)
}

function getZBoundaries(ageYears: number, dataset: Record<string, GenderZData>, sex: string) {
  const useMonthly = ageYears <= 2
  const d = useMonthly ? dataset[sex].monthly : dataset[sex].yearly
  const ageInUnits = useMonthly ? ageYears * 12 : ageYears
  return {
    zm3: interp(d.ages, d.zm3, ageInUnits),
    zm2: interp(d.ages, d.zm2, ageInUnits),
    zm1: interp(d.ages, d.zm1, ageInUnits),
    z0:  interp(d.ages, d.z0,  ageInUnits),
    zp1: interp(d.ages, d.zp1, ageInUnits),
    zp2: interp(d.ages, d.zp2, ageInUnits),
    zp3: interp(d.ages, d.zp3, ageInUnits),
  }
}

export function classifyZScore(
  value: number,
  ageYears: number,
  dataset: Record<string, GenderZData>,
  tipo: 'imc' | 'peso' | 'altura',
  sex: string
): { label: string; zone: string } {
  const b = getZBoundaries(ageYears, dataset, sex)

  if (tipo === 'peso') {
    if (value < b.zm3) return { label: '< -3 DP', zone: 'critical_low' }
    if (value < b.zm2) return { label: '-3 a -2 DP', zone: 'low' }
    if (value <= b.zp2) return { label: '-2 a +2 DP', zone: 'normal' }
    if (value <= b.zp3) return { label: '+2 a +3 DP', zone: 'high' }
    return                    { label: '> +3 DP',     zone: 'critical_high' }
  }

  if (tipo === 'altura') {
    if (value < b.zm3) return { label: '< -3 DP', zone: 'critical_low' }
    if (value < b.zm2) return { label: '-3 a -2 DP', zone: 'low' }
    return                    { label: '≥ -2 DP',    zone: 'normal' }
  }

  // IMC — classification differs by age group
  if (value < b.zm3) return { label: '< -3 DP', zone: 'critical_low' }
  if (value < b.zm2) return { label: '-3 a -2 DP', zone: 'low' }
  if (value <= b.zp1) return { label: '-2 a +1 DP', zone: 'normal' }
  if (value <= b.zp2) return { label: '+1 a +2 DP', zone: 'high' }
  if (value <= b.zp3) return { label: '+2 a +3 DP', zone: 'very_high' }
  return                    { label: '> +3 DP',     zone: 'critical_high' }
}

export function getNutritionalStatus(zone: string, tipo: 'imc' | 'peso' | 'altura', ageYears?: number): string {
  if (tipo === 'peso') {
    const map: Record<string, string> = {
      critical_low: 'Muito Baixo Peso',
      low: 'Baixo Peso',
      normal: 'Peso Adequado',
      high: 'Peso Elevado',
      critical_high: 'Peso Muito Elevado',
    }
    return map[zone] ?? zone
  }
  if (tipo === 'altura') {
    const map: Record<string, string> = {
      critical_low: 'Muito Baixa Estatura',
      low: 'Baixa Estatura',
      normal: 'Estatura Adequada',
    }
    return map[zone] ?? zone
  }
  // IMC — age-dependent labels
  const age = ageYears ?? 0
  if (age < 5) {
    const map: Record<string, string> = {
      critical_low: 'Magreza Acentuada',
      low: 'Magreza',
      normal: 'Eutrofia',
      high: 'Risco de Sobrepeso',
      very_high: 'Sobrepeso',
      critical_high: 'Obesidade',
    }
    return map[zone] ?? zone
  }
  const map: Record<string, string> = {
    critical_low: 'Magreza Acentuada',
    low: 'Magreza',
    normal: 'Eutrofia',
    high: 'Sobrepeso',
    very_high: 'Obesidade',
    critical_high: 'Obesidade Grave',
  }
  return map[zone] ?? zone
}

export function getChartSeries(dataset: Record<string, GenderZData>, sex: string, ageYears: number) {
  const useMonthly = ageYears <= 2
  const d = useMonthly ? dataset[sex].monthly : dataset[sex].yearly
  const ages = useMonthly ? d.ages.map((m: number) => parseFloat((m / 12).toFixed(3))) : d.ages
  return { ages, zm3: d.zm3, zm2: d.zm2, zm1: d.zm1, z0: d.z0, zp1: d.zp1, zp2: d.zp2, zp3: d.zp3 }
}
